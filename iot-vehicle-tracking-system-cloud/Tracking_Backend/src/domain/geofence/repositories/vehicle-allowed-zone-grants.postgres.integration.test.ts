import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';

vi.mock('@/infrastructure/database/pool', async () => {
  const { Client } = await import('pg');
  return { pool: new Client({
    host: process.env.PGHOST ?? '127.0.0.1',
    port: Number(process.env.PGPORT ?? '5432'),
    user: process.env.PGUSER ?? 'ivts_test',
    password: process.env.PGPASSWORD ?? 'ivts_test_password',
    database: process.env.PGDATABASE ?? 'ivts_test_assets',
  }) };
});

import { pool } from '@/infrastructure/database/pool';
import {
  getActiveZoneByVehicleId, getVehiclePositionSnapshot, upsertActiveZone, disableActiveZone,
} from './vehicle-allowed-zone.repository';

const integration = process.env.IVTS_PG_INTEGRATION === '1' ? describe : describe.skip;
const u1 = { userId: 101, role: 'manager', deviceAccessMode: 'assigned' };
const admin = { userId: 1, role: 'admin', deviceAccessMode: 'all' };

const zoneInput = (vehicleId: string, scope: typeof u1) => ({
  vehicleId, scope, centerLat: 10.0, centerLon: 106.0, radiusMeters: 200,
  centerSource: 'map_pick' as const, centerSnapshotAt: null,
  alertMode: 'transition_only' as const, cooldownSec: 300,
  sourceWarning: null, actorId: scope.userId,
});

integration('vehicle allowed-zone mutations and position snapshots are grant scoped', () => {
  beforeAll(async () => {
    if (process.env.PGDATABASE !== 'ivts_test_assets') throw new Error('Unsafe zone fixture database');
    await pool.connect();
    await pool.query('CREATE TEMP TABLE user_device_access(user_id int,device_id text)');
    await pool.query('CREATE TEMP TABLE vehicles(vehicle_id text PRIMARY KEY,plate_number text,device_id text)');
    await pool.query('CREATE TEMP TABLE devices(device_id text PRIMARY KEY,last_latitude float8,latitude float8,last_longitude float8,longitude float8,last_seen_at timestamptz)');
    await pool.query(`CREATE TEMP TABLE vehicle_allowed_zones(
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, vehicle_id text UNIQUE,
      zone_type text, center_lat float8, center_lon float8, radius_m float8,
      center_source text, center_snapshot_at timestamptz, status text,
      last_membership_state text, last_membership_changed_at timestamptz,
      last_alerted_state text, last_alerted_at timestamptz, suppression_until timestamptz,
      alert_mode text, cooldown_sec integer, source_warning_json jsonb,
      created_by int, updated_by int, created_at timestamptz, updated_at timestamptz
    )`);
    await pool.query("INSERT INTO user_device_access VALUES(101,'D1'),(102,'D2')");
    await pool.query("INSERT INTO vehicles VALUES('V1','Plate1','D1'),('V2','Plate2','D2')");
    await pool.query("INSERT INTO devices VALUES('D1',10.1,NULL,106.1,NULL,NOW()),('D2',10.2,NULL,106.2,NULL,NOW())");
  });
  afterAll(async () => { await pool.end(); });

  it('restricts latest position read to the assigned vehicle', async () => {
    expect((await getVehiclePositionSnapshot('V1', u1))?.vehicle_id).toBe('V1');
    expect(await getVehiclePositionSnapshot('V2', u1)).toBeNull();
    expect((await getVehiclePositionSnapshot('V2', admin))?.vehicle_id).toBe('V2');
  });

  it('denies foreign zone inserts and accepts own-fleet/admin changes', async () => {
    expect(await upsertActiveZone(zoneInput('V2', u1))).toBeNull();
    expect((await upsertActiveZone(zoneInput('V1', u1)))?.vehicle_id).toBe('V1');
    expect((await upsertActiveZone(zoneInput('V2', admin)))?.vehicle_id).toBe('V2');
    expect(await upsertActiveZone(zoneInput('V2', u1))).toBeNull();
    expect((await getActiveZoneByVehicleId('V1', u1))?.vehicle_id).toBe('V1');
    expect(await getActiveZoneByVehicleId('V2', u1)).toBeNull();
  });

  it('revokes reads, upserts and disables atomically while retaining admin recovery', async () => {
    await pool.query("DELETE FROM user_device_access WHERE user_id=101 AND device_id='D1'");
    expect(await getVehiclePositionSnapshot('V1', u1)).toBeNull();
    expect(await getActiveZoneByVehicleId('V1', u1)).toBeNull();
    expect(await upsertActiveZone(zoneInput('V1', u1))).toBeNull();
    expect(await disableActiveZone('V1', u1, u1.userId)).toBeNull();
    expect((await getActiveZoneByVehicleId('V1', admin))?.status).toBe('active');
    expect((await disableActiveZone('V1', admin, 1))?.status).toBe('disabled');
  });
});
